"""Full-space search: roles x mixing distributions x het-means/variances.

For each response (DE masks), evaluates a structured ladder with
gse_rp_pilot._fit_structured (R=200 Halton draws, log_len offset):
  fixed | rdm-normal | rdm x {lognormal, triangular, uniform}
  | rdm-normal + het-means | rdm-normal + het-means + het-variances
  | best-dist + het-means + het-variances
then backward-prunes fixed terms with p>0.10 while BIC improves.
Selects lowest BIC among ACCEPT verdicts (fallback: lowest BIC).
Writes best-only coefficient tables + summary (paper auto-wires on landing).
This subsumes the manual pruned refit: significance is enforced in-search.
"""
import os, sys
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gse_rp_pilot import _fit_structured

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "near_miss_hb_ecf.csv")

HB_FEATS = ["AADT", "SL", "NL", "SKD_SP", "IC", "IP", "PA_COM1",
            "PSDSG24", "PSDS1T24", "IV_VL", "IV_M", "RSPSDL5", "RSDSO", "RSDSDL5"]
CRASH_FEATS = ["AADT", "SL", "IP", "MEDSFBar", "PSDS1T24", "PSDSNIL",
               "IV_VL", "RSDSDG10", "RSDSO", "RSDSDL5"]
HB_RDM = ["IC", "IV_M"]
HB_RDM_COR = ["PA_COM1", "RSDSO", "RSDSDL5"]
CR_RDM = ["PSDS1T24", "RSDSDG10"]
CR_RDM_COR = ["SL", "RSDSDL5"]
HELPERS = ["AADT", "SL"]
DISTS = ["normal", "lognormal", "triangular", "uniform"]


def _with_dist(terms, dist):
    return [f"{t.split(':')[0]}:{dist}" for t in terms]


def _sig(p):
    try:
        p = float(p)
    except Exception:
        return ""
    if p < 0.01:
        return "***"
    if p < 0.05:
        return "**"
    if p < 0.10:
        return "*"
    return ""


def _render_tex(ct, caption, label, path):
    ct = ct.copy()
    ct["Sig"] = ct["p"].map(_sig)
    with open(path, "w") as f:
        f.write(f"% Auto-generated by fullspace_search.py\n")
        f.write("\\begin{table}[!ht]\n")
        f.write(f"  \\caption{{{caption}}}\\label{{{label}}}\n")
        f.write("  \\begin{center}\n      \\begin{tabular}{lrrrrc}\n")
        f.write("        \\toprule\n")
        f.write("        Variable & Estimate & Std.Err & z & p & Sig \\\\\n")
        f.write("        \\midrule\n")
        for _, r in ct.iterrows():
            v = str(r["Variable"]).replace("%", "\\%").replace("_", "\\_")
            e = f"{r['Estimate']:+.4f}" if pd.notna(r["Estimate"]) else "--"
            s = f"{r['Std.Err']:.4f}" if pd.notna(r["Std.Err"]) else "--"
            z = f"{r['z']:+.2f}" if pd.notna(r["z"]) else "--"
            p = f"{r['p']:.4f}" if pd.notna(r["p"]) else "--"
            f.write(f"    {v} & {e} & {s} & {z} & {p} & {r['Sig']} \\\\\n")
        f.write("        \\bottomrule\n      \\end{tabular}\n  \\end{center}\n")
        f.write("\\end{table}\n")


ALPHA = 0.10  # significance gate (paper rule)
PENALTY = 10.0  # per insignificant/degenerate coefficient


def _penalised_bic(m):
    ct = m["coef_table"]
    # fixed means (exclude intercept, RND/chol/param/dispersion rows)
    main = ct[~ct["Variable"].str.startswith(("RND", "chol(", "param", "ln("))
               & (ct["Variable"] != "(Intercept)")]
    n_fix = int(((main["p"] > ALPHA) | main["p"].isna()).sum())
    # random SDs must each be significant; untestable (NaN/--) counts as insig
    sd_rows = ct[ct["Variable"].str.startswith("RND sd(")]
    if len(sd_rows) == 0:
        sd_rows = ct[ct["Variable"].str.contains("sd", case=False)
                     & ~ct["Variable"].isin(["(Intercept)"]
                                            + main["Variable"].tolist()
                                            + ["ln(overdispersion)"])]
    n_sd = int(((sd_rows["p"] > ALPHA) | sd_rows["p"].isna()).sum()) if len(sd_rows) else 0
    # correlated-block factor elements carry no individual test -> penalise
    chol_rows = ct[ct["Variable"].str.startswith("chol(")]
    n_chol = int(((chol_rows["p"] > ALPHA) | chol_rows["p"].isna()).sum()) if len(chol_rows) else 0
    # degenerate random means (|mean|>=5 on standardised scale)
    mean_rows = ct[ct["Variable"].str.startswith("RND mean(")]
    n_degen = int((mean_rows["Estimate"].abs() >= 5).sum()) if len(mean_rows) else 0
    # dispersion must stay significant once the random block is in
    try:
        disp_p = float(ct.set_index("Variable").loc["ln(overdispersion)", "p"])
    except KeyError:
        disp_p = float("nan")
    n_disp = 0 if (pd.notna(disp_p) and disp_p <= ALPHA) else 1
    n_insig = n_fix + n_sd + n_chol + n_degen + n_disp
    return m["bic"] + PENALTY * n_insig, n_insig


def search_response(df, feats, y_col, rdm, rdm_cor, tag):
    cands = []
    cands.append((f"{tag}-fixed", dict(rdm=[], rdm_cor=[], helpers=[],
                                       variances_on=False, gse_pack=None)))
    for d in DISTS:
        cands.append((f"{tag}-rdm-{d}",
                      dict(rdm=_with_dist(rdm, d),
                           rdm_cor=_with_dist(rdm_cor, "normal"),
                           helpers=[], variances_on=False, gse_pack=None)))
    cands.append((f"{tag}-rdm-normal-hetM",
                  dict(rdm=_with_dist(rdm, "normal"),
                       rdm_cor=_with_dist(rdm_cor, "normal"),
                       helpers=HELPERS, variances_on=False, gse_pack=None)))
    cands.append((f"{tag}-rdm-normal-hetMV",
                  dict(rdm=_with_dist(rdm, "normal"),
                       rdm_cor=_with_dist(rdm_cor, "normal"),
                       helpers=HELPERS, variances_on=True, gse_pack=None)))
    results = []
    for label, kw in cands:
        print(f"--- {label} ---", flush=True)
        try:
            m, _ = _fit_structured(df, feats, y_col, label, draws_R=200, **kw)
        except Exception as e:
            print(f"  FAILED: {e}", flush=True)
            continue
        pb, ni = _penalised_bic(m)
        print(f"  LL={m['ll']:.1f} BIC={m['bic']:.1f} pBIC={pb:.1f} "
              f"verdict={m.get('verdict')} converged={m['converged']}", flush=True)
        results.append({"label": label, "m": m, "pbic": pb, "n_insig": ni,
                        "kw": kw})
    # Unified selection: lowest penalised BIC wins outright. The penalty
    # already encodes every significance gate (fixed/SD/chol/mean/disp),
    # so no ACCEPT-first filter -- verdict is reported, not filtered on.
    results.sort(key=lambda r: r["pbic"])
    best = results[0]
    print(f"SELECTED {best['label']} pBIC={best['pbic']:.1f} "
          f"verdict={best['m'].get('verdict')}", flush=True)

    # backward prune fixed-only terms (never random-block members) with
    # p>0.10 while penalised BIC improves
    rdm_base = {t.split(":")[0] for t in list(rdm) + list(rdm_cor)}
    cur_feats, cur_kw, cur = list(feats), best["kw"], best["m"]
    for _ in range(5):
        ct = cur["coef_table"]
        main = ct[~ct["Variable"].str.startswith(("RND", "chol(", "param", "ln("))
                   & (ct["Variable"] != "(Intercept)")]
        drop = None
        for i, f_ in enumerate(cur_feats):
            if f_ in rdm_base:
                continue
            row = main.iloc[i] if i < len(main) else None
            if row is not None and (pd.isna(row["p"]) or row["p"] > 0.10):
                drop = f_
                break
        if drop is None:
            break
        trial_feats = [f_ for f_ in cur_feats if f_ != drop]
        if len(trial_feats) < 2:
            break
        try:
            m2, _ = _fit_structured(df, trial_feats, y_col,
                                    best["label"] + f"-no{drop}",
                                    draws_R=200, **cur_kw)
        except Exception as e:
            print(f"  prune {drop} FAILED: {e}", flush=True)
            break
        pb2, _ = _penalised_bic(m2)
        if pb2 < best["pbic"] - 1e-6:
            print(f"  pruned {drop}: pBIC {best['pbic']:.1f} -> {pb2:.1f}", flush=True)
            cur_feats, cur = trial_feats, m2
            best = {"label": best["label"] + f"-no{drop}", "m": m2,
                    "pbic": pb2, "kw": cur_kw}
        else:
            break
    return best, results


def main():
    df = pd.read_csv(DATA, low_memory=False)
    for c in sorted(set(HB_FEATS) | set(CRASH_FEATS)):
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0.0)
    print(f"Loaded {len(df)} rows", flush=True)
    summary = []
    for tag, feats, y, rdm, rdm_cor in [
            ("HB", HB_FEATS, "HB_Total", HB_RDM, HB_RDM_COR),
            ("Crash", CRASH_FEATS, "ObsCrashes", CR_RDM, CR_RDM_COR)]:
        print(f"\n===== {tag} full-space search =====", flush=True)
        best, results = search_response(df, feats, y, rdm, rdm_cor, tag)
        m = best["m"]
        _render_tex(m["coef_table"],
                    f"Full-space best model (roles $\\times$ distributions $\\times$ het-means/variances + pruning): {tag} response ($N=10{{,}}780$)",
                    f"tab:fullspace_{tag.lower()}",
                    os.path.join(HERE, f"fullspace_best_{tag.lower()}.tex"))
        for r in results:
            summary.append({"response": tag, "config": r["label"],
                            "ll": r["m"]["ll"], "bic": r["m"]["bic"],
                            "pbic": r["pbic"],
                            "verdict": r["m"].get("verdict"),
                            "selected": r["label"] == best["label"]})
    pd.DataFrame(summary).to_csv(os.path.join(HERE, "fullspace_summary.csv"), index=False)
    print("Wrote fullspace_best_*.tex + fullspace_summary.csv", flush=True)


if __name__ == "__main__":
    main()
