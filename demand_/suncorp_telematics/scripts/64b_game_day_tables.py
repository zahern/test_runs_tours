"""
64b_game_day_tables.py - LaTeX tables for the focused game-day paper.

Emits exactly two tables, both built from files the pipeline already wrote:
  results/gameday_validation.tex  prediction skill on the 6 held-out fixtures
  results/gameday_sites.tex       per-fixture roster + staffed street names

No new modelling: this only formats stage-59 (59_game_day_search_predict.py)
and stage-60 (60_game_day_mip.py) outputs, so the paper's numbers cannot
drift from the numbers the optimisation actually consumed.
"""
import json
import os

import pandas as pd

PROJ = os.environ.get(
    "SUNCORP_PROJ", r"Z:\test_runs_tours\demand_\suncorp_telematics")
RES = os.path.join(PROJ, "results")


def _esc(s):
    """LaTeX-escape a value destined for table text.

    Underscores are the recurring failure here: a bare "_" in a tabular cell
    is text mode, so TeX emits "Missing $ inserted" and the stray "$"
    desynchronises math mode for every later table in the document.
    """
    return (str(s).replace("\\", "/").replace("_", "\\_")
            .replace("%", "\\%").replace("&", "\\&").replace("#", "\\#"))


def validation_table(out_path):
    with open(os.path.join(RES, "game_day_holdout_metrics.json"),
              encoding="utf-8") as fh:
        blob = json.load(fh)
    m = blob["metrics"]
    a = blob["audit"]
    # handoff (per-fixture scoring) and fixture_variation live inside audit,
    # not at the top level.
    h = a["handoff"]
    fv = a.get("fixture_variation", {})

    rows = [
        ("Predicted segment-bins (6 held-out fixtures)",
         f"{int(m['n_future_rows']):,}"),
        ("Observed segment-bins (for scoring)",
         f"{int(m['n_observed_rows']):,}"),
        ("Bin-level Spearman $\\rho$",
         f"{m['bin_spearman']:.3f}"),
        ("Segment-level Spearman $\\rho$",
         f"{m['segment_spearman']:.3f}"),
        ("Segment-level $\\rho$, single-stage count surface",
         f"{m['count_segment_spearman']:.3f}"),
        ("Count RMSE (events per segment-bin)",
         f"{m['rmse']:.3f}"),
        ("Count MAE (events per segment-bin)",
         f"{m['mae']:.4f}"),
        ("Calibration slope (target 1)",
         f"{m['calibration_slope']:.3f}"),
        ("Per-fixture Pearson $\\rho$, mean over 6",
         f"{h['pearson_mean']:.3f}"),
        ("Per-fixture Pearson $\\rho$, range",
         f"{h['pearson_min']:.3f}--{max(v['pearson_r'] for v in h['per_fixture'].values()):.3f}"),
        ("Top-20 segment recall of observed risk, mean",
         f"{100 * h['top20_coverage_mean']:.1f}\\%"),
        ("Random-siteing floor for the same recall",
         f"{100 * max(v['random_floor'] for v in h['per_fixture'].values()):.2f}\\%"),
        ("Network flow Spearman $\\rho$ (traffic, not risk)",
         f"{m['flow_spearman']:.3f}"),
        ("Variance in top-20 set attributable to the segment, not the fixture",
         f"{fv.get('variance_between_segments_pct', float('nan')):.1f}\\%"),
    ]

    lines = [
        "% gameday_validation.tex - generated by 64b_game_day_tables.py",
        "% source: results/game_day_holdout_metrics.json",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\captionsetup{margin={0.5in,0in}}",
        "\\begin{small}",
        "\\begin{tabular}{lr}",
        "\\toprule",
        "Metric & Value \\\\",
        "\\midrule",
    ]
    lines += [f"{k} & {v} \\\\" for k, v in rows]
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{small}",
        "\\caption{\\textcolor{Highlight}{Prediction skill on the six held-out "
        "fixtures.}\\ Trained on the other "
        f"{a['n_train_fixtures']} fixtures; the segment$\\times$15-minute "
        "surface is scored against what those six fixtures actually produced. "
        "The random floor is the top-20 recall an arbitrary site set would "
        "achieve, and is the value any deployment claim has to beat.}",
        "\\label{tab:gamedayval}",
        "\\end{table}",
    ]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path, len(rows)


def sites_table(out_path):
    sites = pd.read_csv(os.path.join(RES, "game_day_mip_sites.csv"))
    curves = pd.read_csv(os.path.join(RES, "game_day_mip_curves.csv"))

    lines = [
        "% gameday_sites.tex - generated by 64b_game_day_tables.py",
        "% source: results/game_day_mip_sites.csv, game_day_mip_curves.csv",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\captionsetup{margin={0.5in,0in}}",
        "\\begin{scriptsize}",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Fixture & Date & $P_g$ & Moves & Cov\\,1 & Cov\\,$\\bar{P}$ \\\\",
        "\\midrule",
    ]
    mean_p = int(round(sites["squad"].mean()))
    for _, r in sites.iterrows():
        fx = str(r["fixture"])
        date = fx.split("@")[-1].strip() if "@" in fx else ""
        cov1 = float(r["coverage"])
        sub = curves[(curves["fixture"] == fx) & (curves["squad"] == mean_p)]
        covp = float(sub["coverage"].iloc[0]) if len(sub) else float("nan")
        lines.append(
            f"{_esc(fx.split('@')[0].strip())} & {date} & "
            f"{int(r['squad'])} & {int(r['relocations'])} & "
            f"{100 * cov1:.1f}\\% & {100 * covp:.1f}\\% \\\\"
        )
    lines += [
        "\\midrule",
        "\\multicolumn{2}{l}{Mean} & "
        f"{mean_p} & {sites['relocations'].mean():.1f} & "
        f"{100 * sites['coverage'].mean():.1f}\\% & "
        f"{100 * curves[curves['squad'] == mean_p]['coverage'].mean():.1f}\\% \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{scriptsize}",
        "\\caption{\\textcolor{Highlight}{Roster solved independently for "
        "each held-out fixture.} Cov\\,1 is the share of predicted finable "
        "speeding captured by the squad size the MIP chose; Cov\\,$\\bar{P}$ "
        "is the share at the mean squad size, showing the marginal value of "
        "the extra unit.}",
        "\\label{tab:gamedaysites}",
        "\\end{table}",
    ]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path, len(sites)


def street_table(out_path):
    """Which streets the MIP actually staffs -- the operational answer."""
    sites = pd.read_csv(os.path.join(RES, "game_day_mip_sites.csv"))
    first = sites.iloc[0]
    roads = [r.strip() for r in str(first["road_names"]).split("|")]
    osmid = [r.strip() for r in str(first["segment_osmids"]).split("|")]
    latlon = [r.strip() for r in str(first["site_latlon"]).split("|")]
    obsf = [r.strip() for r in str(first["obs_frac"]).split("|")]

    lines = [
        "% gameday_streets.tex - generated by 64b_game_day_tables.py",
        "% source: results/game_day_mip_sites.csv",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\captionsetup{margin={0.5in,0in}}",
        "\\begin{small}",
        "\\begin{tabular}{rllrl}",
        "\\toprule",
        "Site & Street & OSM way & Lat, Lon & Observable \\\\% \\\\",
        "\\midrule",
    ]
    for i, (road, oid, ll, of) in enumerate(zip(roads, osmid, latlon, obsf),
                                            start=1):
        lines.append(
            f"S{i} & {_esc(road)} & {oid} & {ll} & {100 * float(of):.0f}\\% \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{small}",
        "\\caption{\\textcolor{Highlight}{Where to post.} The sites selected "
        "by the MIP, with the fraction of each segment's speeding an officer "
        "stationed at its midpoint can actually observe (100~m of a segment). "
        "The same four street corners are selected for all six held-out "
        "fixtures.}",
        "\\label{tab:gamedaystreets}",
        "\\end{table}",
    ]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path, len(roads)


def coef_table(out_path):
    """Fitted count-model coefficients, with what each term means.

    Reads results/game_day_model_coefs.csv, which stage 59 writes from the
    refit it actually ships, so the table cannot drift from the surface the
    MIP consumed. Role prefixes ("mean(", "sd(", "group_") are how the
    package distinguishes a random-coefficient mean, its standard
    deviation, and a group-level effect; they are unpacked into readable
    labels rather than shown raw.
    """
    c = pd.read_csv(os.path.join(RES, "game_day_model_coefs.csv"))
    c = c.set_index("variable")

    # variable -> (readable label, role in the model)
    meta = {
        "__INTERCEPT__": ("Intercept", "count"),
        "logexp": (r"$\log E_{igt}$ (probe-flow exposure)", "count"),
        "hw_secondary": ("Secondary-road indicator (ref: trunk)", "count"),
        "hw_tertiary": ("Tertiary-road indicator (ref: trunk)", "count"),
        "log_length": (r"$\log L_i$ (segment length)", "count"),
        "in_event": ("In-fixture-window indicator", "count"),
        "rel_hour": (r"Relative hour (15-min bins from kick-off)", "count"),
        "log_att": (r"$\log$ attendance", "count"),
        "event_x_dist": ("Event $\\times$ stadium distance", "count"),
        "fxt_NRL": ("Competition-code indicator (NRL)", "count"),
        "rel_x_dist": ("Relative hour $\\times$ stadium distance", "count"),
        "att_x_dist": ("Attendance $\\times$ stadium distance", "count"),
        "ev_x_lanes": ("Event $\\times$ lane count", "count"),
        "evu_x_att": ("Segment event-uplift $\\times$ attendance", "count"),
        "mean(maxspeed_z)": ("Mean slope, standardised posted speed", "random"),
        "sd(maxspeed_z)": ("SD of that slope", "random"),
        "group_mean(lanes_z)": ("Group-mean slope, standardised lane count", "grouped"),
        "group_sd(lanes_z)": ("SD of the group slope", "grouped"),
    }

    def pfmt(p):
        if p < 1e-4:
            return "$<$0.001"
        return f"{p:.3f}"

    lines = [
        "% gameday_coefs.tex - generated by 64b_game_day_tables.py",
        "% source: results/game_day_model_coefs.csv (stage-59 shipped refit)",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\captionsetup{margin={0.5in,0in}}",
        "\\begin{small}",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Term & Meaning & Coef & SE & $p$ \\\\",
        "\\midrule",
    ]
    order = [k for k in meta if k in c.index]
    for var in order:
        r = c.loc[var]
        # Labels are hand-written LaTeX and already carry their own escapes
        # ($_{}$, \times, \log), so they must NOT go through _esc(): that
        # helper rewrites backslashes for Windows paths and would turn
        # $\log$ into $/log$ and \_ into \_{}.
        label, role = meta[var]
        if role in ("random", "grouped") and var.startswith("sd("):
            sign = ""
        else:
            sign = "" if float(r["coefficient"]) >= 0 else "-"
        coef = f"{sign}{abs(float(r['coefficient'])):.3f}"
        lines.append(
            f"{label} & {role} & {coef} & "
            f"{float(r['std_err']):.3f} & {pfmt(float(r['p_value']))} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{small}",
        "\\caption{\\textcolor{Highlight}{Fitted game-day speeding model.} "
        "Negative-binomial count stage on the segment$\\times$15-minute "
        "panel, refitted after structure search (13 fixed terms, one normal "
        "random coefficient, one grouped coefficient). The exposure "
        "elasticity $\\hat\\beta_E=1.097$ against a theoretical value of $1$ "
        "is the single most important check on the model: a 1\\% increase in "
        "exposure raises expected speeding by 0.97\\%. Terms marked "
        "\\emph{random} and \\emph{grouped} are slopes that vary across "
        "segments; their SD terms are scale parameters and carry no "
        "direction.}",
        "\\label{tab:gamedaycoef}",
        "\\end{table}",
    ]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path, len(order)


def street_breakdown_table(out_path, top_n=14):
    """How many segments the highest-risk streets are split into.

    OSM represents one physical street as many separate ways, so a reader
    seeing "Grey Street 2/31" needs to know that 31 is a fact about the
    network encoding, not 31 separate streets. This table states it.

    Labels come from the SAME loader the figure uses (65_gameday_figures.
    load_ways), so a street that OSM leaves unnamed is reported as
    "motorway slip road (unlinked)" rather than the string "unnamed".
    """
    import importlib.util
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location(
        "_gdfig", os.path.join(here, "65_gameday_figures.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    ways = mod.load_ways()

    pred = pd.read_csv(os.path.join(RES, "game_day_top20_per_game.csv"))
    pred["label"] = pred["road_osmid"].map(ways["label"]).fillna("unknown road")
    best = (pred.groupby("label", observed=True)["pred_speeding"]
            .max().sort_values(ascending=False))
    nseg = ways["label"].value_counts().to_dict()

    lines = [
        "% gameday_streetbreakdown.tex - generated by 64b_game_day_tables.py",
        "% source: results/game_day_top20_per_game.csv + street breakdown",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\captionsetup{margin={0.5in,0in}}",
        "\\begin{scriptsize}",
        "\\begin{tabular}{lrrl}",
        "\\toprule",
        "Street & Segments & Best seg. & Peak predicted \\\\",
        "\\midrule",
    ]
    for name in best.head(top_n).index:
        n = int(nseg.get(name, 1))
        lines.append(
            f"{_esc(name)} & {n} & {best[name]:.1f} & "
            f"{100 * best[name] / float(best.iloc[0]):.0f}\\% \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{scriptsize}",
        "\\caption{\\textcolor{Highlight}{One street, many segments.} OSM "
        "splits a single physical street into separate ways, so a street "
        "carrying the most predicted speeding can appear as dozens of "
        "segments. Figures label these \\texttt{Street k/n}, where $n$ is "
        "the number of OSM segments the street breaks into and $k$ ranks "
        "them by predicted mass, so the segment that actually carries the "
        "risk is $k{=}1$.}",
        "\\label{tab:streetbreak}",
        "\\end{table}",
    ]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path, min(top_n, len(best))


