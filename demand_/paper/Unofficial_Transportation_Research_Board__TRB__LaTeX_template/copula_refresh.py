"""Refresh the retired joint-MLE copula comparison on the current N=10,780 sample.

Replaces the provisional-generation Tables tab:copula_joint / tab:copula_pred
(N=10,302, non-converged Hessians, negative LRs) with:

  * IFM re-estimation on DE-spec margins with multi-start optimisation
    (Frank / Gaussian / Kimeldorf-Sampson), clip audit included;
  * Joint-MLE attempt via nearmiss_hb_analysis.fit_bivariate_copula
    (margins + theta optimised together), with convergence flag;
  * A refreshed tab_copula_joint.tex + copula_joint_refresh.csv.

The stabilised IFM result (copula_joe.tex, all p<0.001) remains the reported
aggregate-copula estimate; this script supplies the queued joint-MLE check.

Usage (HPC): python -u copula_refresh.py [--data near_miss_hb_ecf.csv]
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nearmiss_hb_analysis import fit_model, fit_bivariate_copula
from run_rp_check import HB_FEATS, CRASH_FEATS

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(HERE, "near_miss_hb_ecf.csv"))
    ap.add_argument("--out-dir", default=HERE)
    args = ap.parse_args()

    df = pd.read_csv(args.data, low_memory=False)
    for c in sorted(set(HB_FEATS) | set(CRASH_FEATS)):
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0.0)
    print(f"Loaded {len(df)} rows", flush=True)

    print("Fitting DE-spec margins ...", flush=True)
    m_hb = fit_model(df, HB_FEATS, "HB_Total", "log_len", label="HBfx")
    m_cr = fit_model(df, CRASH_FEATS, "ObsCrashes", "log_len", label="CRfx")
    print(f"HB LL={m_hb['ll']:.1f} BIC={m_hb['bic']:.1f}; "
          f"Crash LL={m_cr['ll']:.1f} BIC={m_cr['bic']:.1f}", flush=True)

    rows = []
    for cop in ["frank", "normal", "kimeldorf"]:
        print(f"--- joint MLE: {cop} ---", flush=True)
        try:
            r = fit_bivariate_copula(df, "HB_Total", m_hb, m_cr, copula_name=cop)
            theta = r.get("theta", np.nan)
            ll = r.get("ll_joint", r.get("ll", np.nan))
            bic = r.get("bic_joint", r.get("bic", np.nan))
            conv = r.get("converged", "NA")
            print(f"{cop}: theta={theta} LL={ll} BIC={bic} converged={conv}",
                  flush=True)
            rows.append({"copula": cop, "theta": theta, "ll": ll,
                         "bic": bic, "converged": conv})
        except Exception as e:  # noqa: BLE001 - must log, not crash the batch
            print(f"{cop} FAILED: {e}", flush=True)
            rows.append({"copula": cop, "theta": np.nan, "ll": np.nan,
                         "bic": np.nan, "converged": f"ERROR: {e}"})

    res = pd.DataFrame(rows)
    # Independence baseline on the same margins.
    ll_indep = m_hb["ll"] + m_cr["ll"]
    k_indep = m_hb["k"] + m_cr["k"]
    n = m_hb["n"]
    bic_indep = k_indep * np.log(n) - 2 * ll_indep
    res["ll_indep"] = ll_indep
    res["bic_indep"] = bic_indep
    res["dBIC"] = res["bic"] - bic_indep
    res["lr"] = 2 * (res["ll"] - ll_indep)
    from scipy import stats as st
    res["lr_p"] = res["lr"].apply(
        lambda v: float(1 - st.chi2.cdf(max(v, 0.0), df=1)) if pd.notna(v) else np.nan)
    res.to_csv(os.path.join(args.out_dir, "copula_joint_refresh.csv"), index=False)

    # Best-of-3 must be computed from the data, not hardcoded: job 25256289
    # showed Kimeldorf BIC=158,788 < Frank 159,035 < Normal 159,621, so the
    # old hardcoded "Normal (best of 3)" label was wrong.
    best_cop = None
    try:
        if len(res.dropna(subset=["bic"])):
            best_cop = res.loc[res["bic"].idxmin(), "copula"]
    except Exception:
        best_cop = None
    base_names = {"frank": "Frank", "normal": "Gaussian",
                  "kimeldorf": "Kimeldorf--Sampson"}
    with open(os.path.join(args.out_dir, "tab_copula_joint_refreshed.tex"), "w") as f:
        f.write("% Auto-generated by copula_refresh.py (current N=10,780 sample)\n")
        f.write("% NOTE: margins fixed at DE-spec NB fits, only theta optimised "
                "(IFM); 'joint MLE' in older captions means IFM joint score.\n")
        f.write("\\begin{table}[!ht]\n")
        f.write("  \\caption{Bivariate NB Copula Comparison (refreshed IFM, "
                "$N=10{,}780$)}\\label{tab:copula_joint_refreshed}\n")
        f.write("  \\begin{center}\n")
        f.write("    \\begin{tabular}{lrrrrrrc}\n")
        f.write("      \\toprule\n")
        f.write("      Copula & $\\hat\\theta$ & LL & BIC & $\\Delta$BIC "
                "& LR & $p$ & Converged \\\\\n")
        f.write("      \\midrule\n")
        f.write(f"      Independence & --- & {ll_indep:,.1f} & {bic_indep:,.1f} "
                "& 0 & --- & --- & --- \\\\\n")
        for _, r in res.iterrows():
            th = f"{r['theta']:.3f}" if pd.notna(r['theta']) else "---"
            ll_s = f"{r['ll']:,.1f}" if pd.notna(r['ll']) else "---"
            b_s = f"{r['bic']:,.1f}" if pd.notna(r['bic']) else "---"
            d_s = f"{r['dBIC']:+,.1f}" if pd.notna(r['dBIC']) else "---"
            lr_s = f"{r['lr']:,.1f}" if pd.notna(r['lr']) else "---"
            p_s = f"{r['lr_p']:.3f}" if pd.notna(r['lr_p']) else "---"
            name = base_names.get(r["copula"], r["copula"])
            if r["copula"] == best_cop:
                name += " (best of 3)"
            f.write(f"      {name} & {th} & {ll_s} & {b_s} & {d_s} & {lr_s} "
                    f"& {p_s} & {r['converged']} \\\\\n")
        f.write("      \\bottomrule\n")
        f.write("    \\end{tabular}\n")
        f.write("  \\end{center}\n")
        f.write("\\end{table}\n")
    print("Wrote tab_copula_joint_refreshed.tex / copula_joint_refresh.csv",
          flush=True)


if __name__ == "__main__":
    main()
