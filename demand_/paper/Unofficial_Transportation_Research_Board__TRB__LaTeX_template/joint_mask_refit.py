"""Significance pruning for the Gumbel joint-searched masks.

Reads the promoted eb_search_joint_best.csv (Gumbel s45 winner: HB 25 /
crash 16 vars), refits each mask as a fixed-effect NB on the full N=10,780
sample under the VMT-years exposure offset, and backward-eliminates to
p<0.10 -- the paper's best-models-only rule. The joint search scores raw
joint BIC (no per-coefficient penalty), so its masks are large; this job
supplies the coefficient tables + significance verdicts the search itself
does not record (no thetas/coefs are stored in eb_search_joint_best.csv).

Outputs (project root = paper inputs, new filenames):
  joint_mask_refit_hb.tex / .csv      pruned HB-mask coefficient table
  joint_mask_refit_crash.tex / .csv   pruned crash-mask coefficient table
  joint_mask_refit_verdict.csv        kept/dropped vars, LL/BIC/k, verdicts

Usage (HPC): python -u joint_mask_refit.py [--masks-csv eb_search_joint_best.csv]
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nearmiss_hb_analysis import fit_model, VLABEL  # same estimator as paper
from exposure import OFF, add_exposure_offsets

HERE = os.path.dirname(os.path.abspath(__file__))
MCR_MIN_VERSION = (1, 0, 154)
ALPHA = 0.10  # significance gate (matches penalised-BIC penalty rule)


def _V(c):
    return VLABEL.get(c, c)


def check_mcr_version():
    try:
        import metacountregressor as mcr  # noqa: F401
        try:
            from importlib.metadata import version as _pkg_version
            ver = _pkg_version("metacountregressor")
        except Exception:
            ver = getattr(mcr, "__version__", "0.0.0")
    except Exception:
        print("FATAL: metacountregressor not importable -- refusing to run",
              flush=True)
        sys.exit(2)
    try:
        tup = tuple(int(x) for x in ver.split(".")[:3])
    except ValueError:
        tup = (0, 0, 0)
    print(f"metacountregressor {ver} (required >= 1.0.154)", flush=True)
    if tup < MCR_MIN_VERSION:
        print(f"FATAL: metacountregressor {ver} < 1.0.154 -- refusing to run",
              flush=True)
        sys.exit(2)
    return ver


def backward_eliminate(df, feats, y_col, label, alpha=ALPHA):
    """Fit NB, drop worst p>alpha covariate, repeat until fully significant."""
    feats = list(feats)
    _missing = [c for c in feats if c not in df.columns]
    if _missing:
        raise RuntimeError(f"[{label}] feats absent from data columns: {_missing}")
    steps, dropped = [], []
    while True:
        m = fit_model(df, feats, y_col, OFF, label=label)
        ct = m["coef_table"]
        verbose = [_V(f) for f in feats]
        inv = {_V(f): f for f in feats}
        cand = ct[ct["Variable"].isin(verbose)]
        if len(cand) == 0:
            break
        worst = cand.loc[cand["p"].idxmax()]
        if float(worst["p"]) <= alpha:
            steps.append((list(feats), m))
            break
        steps.append((list(feats), m))
        worst_raw = inv.get(worst["Variable"], worst["Variable"])
        dropped.append((worst_raw, float(worst["p"])))
        feats = [f for f in feats if f != worst_raw]
        print(f"[{label}] drop {worst['Variable']} ({worst_raw}) "
              f"p={worst['p']:.4f} -> {len(feats)} vars", flush=True)
        if len(feats) < 2:
            m = fit_model(df, feats, y_col, OFF, label=label)
            steps.append((list(feats), m))
            break
    if not steps:
        raise RuntimeError(f"[{label}] first fit returned no searched "
                           f"covariates -- check estimator/data columns")
    return feats, steps[-1][1], dropped


def write_coef_tex(m, feats, path, caption, label, joint_bic):
    ct = m["coef_table"]
    allowed = set([_V(f) for f in feats] + ["(Intercept)", "ln(overdispersion)"])
    with open(path, "w") as f:
        f.write("% Auto-generated by joint_mask_refit.py (Gumbel joint masks, "
                f"pruned to p<{ALPHA})\n")
        f.write(f"% Model: {label}: LL={m['ll']:.2f}, BIC={m['bic']:.2f}, "
                f"k={m['k']}, n={m['n']}, joint-BIC={joint_bic:.1f}\n")
        f.write("\\begin{table}[!ht]\n")
        f.write(f"  \\caption{{{caption}}}\\label{{{label}}}\n")
        f.write("  \\begin{center}\n")
        f.write("      \\begin{tabular}{lrrrrc}\n")
        f.write("        \\toprule\n")
        f.write("        Variable & Estimate & IRR & z & p & Sig \\\\\n")
        f.write("        \\midrule\n")
        for _, r in ct.iterrows():
            v = r["Variable"]
            if v.startswith(("RND", "chol", "ln(")) or v not in allowed:
                if v not in ("(Intercept)", "ln(overdispersion)"):
                    continue
            sig = "***" if r["p"] < 0.01 else ("**" if r["p"] < 0.05
                  else ("*" if r["p"] < 0.10 else ""))
            irr = (f"{np.exp(r['Estimate']):.4f}"
                   if ("RND" not in v and "chol" not in v and "ln(" not in v)
                   else "--")
            f.write(f"    {v} & {r['Estimate']:+.4f} & {irr} & "
                    f"{r['z']:+.2f} & {r['p']:.4f} & {sig} \\\\\n")
        f.write("        \\bottomrule\n")
        f.write("      \\end{tabular}\n")
        f.write("  \\end{center}\n")
        f.write(f"  \\footnotesize{{Note: $N$ = {m['n']:,} segments. Negative "
                "Binomial (NB) regression. All predictors standardized. "
                f"Gumbel joint-searched mask, backward elimination to $p<{ALPHA}$; "
                "zero insignificant coefficients retained.}\n")
        f.write("\\end{table}\n")
    print(f"Wrote {path} (k={m['k']}, BIC={m['bic']:.1f})", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(HERE, "near_miss_hb_ecf.csv"))
    ap.add_argument("--out-dir", default=HERE)
    ap.add_argument("--masks-csv",
                    default=os.path.join(HERE, "eb_search_joint_best.csv"))
    args = ap.parse_args()

    check_mcr_version()

    masks = pd.read_csv(args.masks_csv).iloc[0]
    hb_mask = [c for c in str(masks["hb_features"]).split(";") if c]
    cr_mask = [c for c in str(masks["crash_features"]).split(";") if c]
    joint_bic = float(masks["joint_bic"])
    print(f"Joint masks from {args.masks_csv}: copula={masks.get('copula', '?')}, "
          f"HB({len(hb_mask)}) CR({len(cr_mask)}), joint-BIC={joint_bic:.1f}",
          flush=True)

    df = pd.read_csv(args.data, low_memory=False)
    df = add_exposure_offsets(df)
    for c in sorted(set(hb_mask) | set(cr_mask)):
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0.0)
    print(f"Loaded {len(df)} rows", flush=True)

    rows = []
    for feats, y, tag, cap, lab, stem in [
        (hb_mask, "HB_Total", "JointMask-HB",
         "Gumbel Joint-Searched Mask (significance-pruned, $p<0.10$): Hard-Braking Response",
         "tab:joint_mask_hb", "hb"),
        (cr_mask, "ObsCrashes", "JointMask-Crash",
         "Gumbel Joint-Searched Mask (significance-pruned, $p<0.10$): Crash Response",
         "tab:joint_mask_crash", "crash"),
    ]:
        kept, m, dropped = backward_eliminate(df, feats, y, tag)
        ct = m["coef_table"]
        ok = all(float(ct[ct["Variable"] == _V(v)]["p"].iloc[0]) <= ALPHA
                 for v in kept if len(ct[ct["Variable"] == _V(v)]))
        verdict = "PASS" if ok else "FAIL"
        print(f"[{tag}] kept {len(kept)}/{len(feats)} "
              f"LL={m['ll']:.1f} BIC={m['bic']:.1f} -> {verdict}", flush=True)
        write_coef_tex(m, kept,
                       os.path.join(args.out_dir,
                                    f"joint_mask_refit_{stem}.tex"),
                       cap, lab, joint_bic)
        ct.to_csv(os.path.join(args.out_dir,
                               f"joint_mask_refit_{stem}.csv"), index=False)
        rows.append({"response": tag, "n_start": len(feats),
                     "n_kept": len(kept),
                     "dropped": ";".join(f"{v}(p={p:.3f})" for v, p in dropped),
                     "ll": m["ll"], "bic": m["bic"], "k": m["k"],
                     "joint_bic": joint_bic, "verdict": verdict})
    pd.DataFrame(rows).to_csv(os.path.join(args.out_dir,
                                           "joint_mask_refit_verdict.csv"),
                              index=False)
    print("Joint-mask refits complete.", flush=True)


if __name__ == "__main__":
    main()
