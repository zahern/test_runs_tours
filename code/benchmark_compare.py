#!/usr/bin/env python
"""Compare benchmark models (B0-B3, scipy/statsmodels) against the HPC
Larch/JAX pipeline arms (E0/E1/E2): the table the pipeline must beat.

Reads (when present):
  runs/benchmark_exampville/benchmark_metrics.json      (local benchmark)
  runs/benchmark_exampville_hpc/benchmark_metrics.json  (HPC benchmark rerun)
  runs/exampville_ab/exampville_metrics.json            (HPC pipeline arms)

Writes:
  benchmark_comparison_table.tex   (auto-generated paper table; PENDING cells
      where an HPC number does not exist yet)

Usage:
    python benchmark_compare.py [--outdir runs/benchmark_exampville]
"""
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name):
    for cand in (os.path.join(_HERE, "runs", name, "benchmark_metrics.json"),
                 os.path.join(_HERE, "runs", name, "exampville_metrics.json")):
        if os.path.exists(cand):
            with open(cand) as f:
                return json.load(f)
    return {}


def _fmt(x, digits=4):
    try:
        import numpy as np
        v = float(x)
        return f"{v:.{digits}f}" if np.isfinite(v) else "---"
    except Exception:
        return "PENDING"


def main():
    outdir = os.path.join(_HERE, "runs", "benchmark_exampville")
    for i, a in enumerate(sys.argv[1:]):
        if a == "--outdir" and i + 1 < len(sys.argv[1:]):
            outdir = sys.argv[1:][i + 1]
    bench = _load("benchmark_exampville")
    bench_hpc = _load("benchmark_exampville_hpc")
    pipe = _load("exampville_ab")
    _b = (bench.get("arms") or {})
    _p = (pipe.get("arms") or {})

    rows = [
        ("B0 CDAP (MNLogit)",
         _b.get("B0", {}).get("mae"), None,
         (_p.get("E1_s0", {}).get("ll"), _p.get("E2_s0", {}).get("ll"))),
        ("B1 frequency (Poisson)",
         _b.get("B1", {}).get("mean_mae"), _b.get("B1", {}).get("ll"),
         (_p.get("E1_s1", {}).get("work_mean_mae"),
          _p.get("E2_s1", {}).get("work_mean_mae"))),
        ("B2 mode (flat MNL)",
         _b.get("B2", {}).get("mode_mae"),
         _b.get("B2", {}).get("ll"),
         (_p.get("E1", {}).get("mode_mae"), _p.get("E2", {}).get("mode_mae"))),
        ("B3 destination (MNL, 20 alts)",
         _b.get("B3", {}).get("dest_mae"),
         _b.get("B3", {}).get("ll"),
         (_p.get("E1", {}).get("dest_mae"), _p.get("E2", {}).get("dest_mae"))),
    ]
    print("=== benchmark (B) vs pipeline (E) ===")
    for _name, _m1, _m2, (_e1, _e2) in rows:
        print(f"{_name}: bench={_fmt(_m1)} / {_fmt(_m2)} | "
              f"E1={_fmt(_e1)} E2={_fmt(_e2)}")

    _tex = os.path.join(outdir, "benchmark_comparison_table.tex")
    os.makedirs(outdir, exist_ok=True)
    with open(_tex, "w") as f:
        f.write("% Auto-generated by benchmark_compare.py — DO NOT EDIT BY HAND.\n")
        f.write("\\begin{table}[!ht]\n")
        f.write("  \\caption{Benchmark models vs.\\ pipeline arms on Exampville. "
                "Benchmarks (B0--B3, scipy/statsmodels, flat MNL) are the bar the "
                "Larch nested/search arms (E0--E2) must beat. PENDING = awaiting "
                "the HPC run.}\\label{tab:benchmark_compare}\n")
        f.write("  \\begin{center}\n")
        f.write("    \\begin{tabular}{lrrrr}\n")
        f.write("      \\toprule\n")
        f.write("      Model & Bench MAE & Bench LL & E1 & E2 \\\\\n")
        f.write("      \\midrule\n")
        for _name, _m1, _m2, (_e1, _e2) in rows:
            f.write(f"      {_name} & {_fmt(_m1)} & {_fmt(_m2)} & "
                    f"{_fmt(_e1)} & {_fmt(_e2)} \\\\\n")
        f.write("      \\bottomrule\n")
        f.write("    \\end{tabular}\n")
        f.write("  \\end{center}\n")
        f.write("\\end{table}\n")
    print(f"wrote {_tex}")


if __name__ == "__main__":
    main()
