#!/usr/bin/env python3
"""
Finalisation: held-out prediction + paper-ready master model table.
===================================================================
Turns the search outputs into the evidence the paper was missing:
  * genuine out-of-sample prediction for the HB and crash models
    (random K-fold, leave-one-LGA-out, and temporal for HB),
  * one consolidated "best models" table (HB / Crash / Joint side by side)
    with in-sample fit AND held-out performance AND transfer verdicts.

Called from hb_vs_crash_prediction_search.main() after the search + transfer +
copula steps complete.
"""
import os
import numpy as np
import pandas as pd

import validation as V


# --------------------------------------------------------------------------
def run_holdout(df, panel, hb_feats, cr_feats, out_dir, kfolds=5,
                region_col="lga"):
    """Run all held-out designs for both responses; write CSVs; return dict."""
    print(f"\n{'#'*70}\n  HELD-OUT PREDICTION (K-fold / spatial / temporal)\n{'#'*70}")
    res = {}

    # 0) parameterisation self-check (guards the OOS log-lik)
    ok, _, _ = V.self_check(df, hb_feats[:4] if len(hb_feats) >= 4 else hb_feats,
                            "nm_total")
    res["selfcheck_ok"] = bool(ok)
    if not ok:
        print("  WARNING: NB2 reconstruction self-check FAILED — OOS LL suspect")

    specs = [("HB", hb_feats, "nm_total"), ("CRASH", cr_feats, "ObsCrashes")]

    # 1) random K-fold
    kf_rows = []
    res["kfold"] = {}
    for name, feats, y in specs:
        agg, per = V.kfold_oos(df, feats, y, k=kfolds, label=name)
        res["kfold"][name] = agg
        per["response"] = name
        kf_rows.append(per)
    pd.concat(kf_rows, ignore_index=True).to_csv(
        os.path.join(out_dir, "oos_kfold.csv"), index=False)
    pd.DataFrame([{"response": n, **res["kfold"][n]} for n, _, _ in specs]).to_csv(
        os.path.join(out_dir, "oos_kfold_summary.csv"), index=False)

    # 2) leave-one-LGA-out spatial transfer
    sp_rows = []
    res["spatial"] = {}
    for name, feats, y in specs:
        agg, per = V.spatial_transfer(df, feats, y, region_col=region_col,
                                      label=name)
        res["spatial"][name] = agg
        if per is not None:
            per["response"] = name
            sp_rows.append(per)
    if sp_rows:
        pd.concat(sp_rows, ignore_index=True).to_csv(
            os.path.join(out_dir, "transfer_spatial.csv"), index=False)

    # 3) temporal transfer (HB only — crashes are static multi-year totals)
    res["temporal"] = V.temporal_transfer(df, panel, hb_feats, label="HB")
    if res["temporal"] is not None:
        pd.DataFrame([res["temporal"]]).to_csv(
            os.path.join(out_dir, "transfer_temporal.csv"), index=False)

    _write_holdout_tex(res, out_dir)
    return res


def _write_holdout_tex(res, out_dir):
    """Paper-ready LaTeX includes for the held-out designs (auto-populated)."""
    kf, sp, tp = res.get("kfold", {}), res.get("spatial", {}), res.get("temporal")
    names = {"HB": "Hard-braking", "CRASH": "Crashes"}

    # K-fold OOS
    with open(os.path.join(out_dir, "oos_kfold.tex"), "w") as f:
        f.write("% auto-generated by finalize (K-fold out-of-sample)\n")
        f.write("\\begin{tabular}{lrrrrr}\n\\hline\n")
        f.write("Response & OOS LL/obs & RMSE (log) & MAE & Pearson $r$ "
                "& Spearman $\\rho$ \\\\\n\\hline\n")
        for key in ("HB", "CRASH"):
            a = kf.get(key)
            if not a:
                continue
            f.write(f"{names[key]} & {_fmt(a.get('oos_ll_per_obs'),3)} & "
                    f"{_fmt(a.get('rmse_log'),3)} & {_fmt(a.get('mae'),2)} & "
                    f"{_fmt(a.get('pearson'),3)} & {_fmt(a.get('spearman'),3)} "
                    f"\\\\\n")
        f.write("\\hline\n\\end{tabular}\n")

    # Leave-one-LGA-out spatial transfer
    with open(os.path.join(out_dir, "transfer_spatial.tex"), "w") as f:
        f.write("% auto-generated by finalize (leave-one-LGA-out)\n")
        f.write("\\begin{tabular}{lrrr}\n\\hline\n")
        f.write("Response & LGAs & Beat naive base & Mean Spearman $\\rho$ "
                "\\\\\n\\hline\n")
        for key in ("HB", "CRASH"):
            a = sp.get(key)
            if not a:
                continue
            f.write(f"{names[key]} & {a.get('n_regions','--')} & "
                    f"{a.get('regions_beating_baseline','--')}/"
                    f"{a.get('n_regions','--')} & "
                    f"{_fmt(a.get('mean_spearman'),3)} \\\\\n")
        f.write("\\hline\n\\end{tabular}\n")

    # Temporal transfer (HB)
    with open(os.path.join(out_dir, "transfer_temporal.tex"), "w") as f:
        f.write("% auto-generated by finalize (temporal transfer, HB)\n")
        if tp is None:
            f.write("\\emph{Temporal transfer pending panel data.}\n")
        else:
            f.write("\\begin{tabular}{lr}\n\\hline\n")
            f.write("Hard-braking temporal transfer & Value \\\\\n\\hline\n")
            f.write(f"Train months & {tp.get('train_months','--')} \\\\\n")
            f.write(f"Test months & {tp.get('test_months','--')} \\\\\n")
            f.write(f"Pearson $r$ & {_fmt(tp.get('pearson'),3)} \\\\\n")
            f.write(f"Spearman $\\rho$ & {_fmt(tp.get('spearman'),3)} \\\\\n")
            f.write(f"RMSE (log) & {_fmt(tp.get('rmse_log'),3)} \\\\\n")
            f.write("\\hline\n\\end{tabular}\n")


# --------------------------------------------------------------------------
def _fmt(x, nd=2):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    return f"{x:.{nd}f}"


def build_master_table(df, hb_de, cr_de, hb_feats, cr_feats, st, encomp,
                       copula, holdout, hb_mcr, cr_mcr, out_dir):
    """Consolidated best-models table (CSV + LaTeX) — the spine of the results."""
    print(f"\n{'#'*70}\n  MASTER BEST-MODELS TABLE\n{'#'*70}")

    kf = holdout.get("kfold", {})
    sp = holdout.get("spatial", {})
    tp = holdout.get("temporal")

    def row(name, fit, feats, mcr):
        k = kf.get(name, {})
        s = sp.get(name) or {}
        return {
            "response": name,
            "n_features": len(feats),
            "insample_ll": fit["ll"],
            "insample_bic": fit["bic"],
            "insample_aic": fit["aic"],
            "k_params": fit["k"],
            "mcr_bic": (mcr.get("bic") if isinstance(mcr, dict) else None),
            "oos_ll_per_obs": k.get("oos_ll_per_obs"),
            "oos_rmse": k.get("rmse"),
            "oos_rmse_log": k.get("rmse_log"),
            "oos_mae": k.get("mae"),
            "oos_pearson": k.get("pearson"),
            "oos_spearman": k.get("spearman"),
            "spatial_regions": s.get("n_regions"),
            "spatial_beating_base": s.get("regions_beating_baseline"),
            "spatial_mean_spearman": s.get("mean_spearman"),
            "features": ";".join(feats),
        }

    rows = [row("HB", hb_de, hb_feats, hb_mcr),
            row("CRASH", cr_de, cr_feats, cr_mcr)]
    if tp is not None:
        rows[0]["temporal_spearman"] = tp.get("spearman")
        rows[0]["temporal_pearson"] = tp.get("pearson")

    master = pd.DataFrame(rows)
    master.to_csv(os.path.join(out_dir, "best_models_master.csv"), index=False)

    # ---- transfer / joint block --------------------------------------------
    best_cn = copula["best_copula"]
    cop_fit = copula["fits"][best_cn]
    joint = {
        "hb_to_crash_dbic": st["penalty_hb"],
        "crash_to_hb_dbic": st["penalty_cr"],
        "transfer_verdict": st["verdict"],
        "encompassing_lr": encomp["lr_stat"],
        "encompassing_p": encomp["p"],
        "encompassing_dbic": encomp["bic_u"] - encomp["bic_r"],
        "best_copula": best_cn,
        "copula_theta": cop_fit["theta"],
        "copula_bic": cop_fit["bic_joint"],
        "independence_bic": copula["bic_indep"],
        "copula_dbic_vs_indep": cop_fit["bic_joint"] - copula["bic_indep"],
        "copula_lr": cop_fit["lr_stat"],
        "copula_p": cop_fit["p_lr"],
    }
    pd.DataFrame([joint]).to_csv(
        os.path.join(out_dir, "best_models_joint.csv"), index=False)

    # ---- LaTeX -------------------------------------------------------------
    tex = os.path.join(out_dir, "best_models_master.tex")
    with open(tex, "w") as f:
        f.write("% auto-generated by finalize.build_master_table\n")
        f.write("\\begin{tabular}{lrrrrrrr}\n\\hline\n")
        f.write("Model & \\#feat & BIC & OOS LL/obs & OOS RMSE & OOS $\\rho$ "
                "& LGA folds & LGA $\\rho$ \\\\\n")
        f.write("      &        &     & (K-fold)   & (log)    & (K-fold) "
                "& beat base & (mean) \\\\\n\\hline\n")
        for r in rows:
            f.write(
                f"{'Hard-braking' if r['response']=='HB' else 'Crashes'} & "
                f"{r['n_features']} & {_fmt(r['insample_bic'],0)} & "
                f"{_fmt(r['oos_ll_per_obs'],3)} & {_fmt(r['oos_rmse_log'],3)} & "
                f"{_fmt(r['oos_spearman'],3)} & "
                f"{r.get('spatial_beating_base','--')}/"
                f"{r.get('spatial_regions','--')} & "
                f"{_fmt(r['spatial_mean_spearman'],3)} \\\\\n")
        f.write("\\hline\n")
        f.write("\\multicolumn{8}{l}{\\footnotesize Transfer: "
                f"HB$\\to$Crash $\\Delta$BIC={joint['hb_to_crash_dbic']:+.1f}, "
                f"Crash$\\to$HB $\\Delta$BIC={joint['crash_to_hb_dbic']:+.1f} "
                f"({joint['transfer_verdict']}). "
                f"Encompassing LR={joint['encompassing_lr']:.1f} "
                f"($p={joint['encompassing_p']:.1e}$, "
                f"$\\Delta$BIC={joint['encompassing_dbic']:+.1f}). "
                f"Joint copula: {best_cn} "
                f"$\\Delta$BIC={joint['copula_dbic_vs_indep']:+.1f} vs indep.}} \\\\\n")
        f.write("\\hline\n\\end{tabular}\n")

    # console summary
    print("\n  " + "=" * 66)
    print(f"  {'Model':<14}{'#f':>4}{'BIC':>11}{'OOS LL/o':>11}"
          f"{'OOS RMSE':>10}{'OOS rho':>9}{'LGA rho':>9}")
    print("  " + "-" * 66)
    for r in rows:
        print(f"  {('Hard-braking' if r['response']=='HB' else 'Crashes'):<14}"
              f"{r['n_features']:>4}{_fmt(r['insample_bic'],0):>11}"
              f"{_fmt(r['oos_ll_per_obs'],3):>11}{_fmt(r['oos_rmse_log'],3):>10}"
              f"{_fmt(r['oos_spearman'],3):>9}"
              f"{_fmt(r['spatial_mean_spearman'],3):>9}")
    print("  " + "=" * 66)
    print(f"  Transfer verdict: {joint['transfer_verdict']}  |  "
          f"Encompassing p={joint['encompassing_p']:.2e}  |  "
          f"Joint {best_cn} dBIC={joint['copula_dbic_vs_indep']:+.1f}")
    print(f"  -> {tex}")
    return master, joint
