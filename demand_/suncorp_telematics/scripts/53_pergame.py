"""
53_pergame.py
========================================================================
Per-fixture rosters with leave-one-fixture-out prediction, on the REAL
surfaces (results/surfaces.npz).

For each fixture the space-time surface is predicted from the other
fixtures: the mean of the training surfaces, rescaled by a fitted crowd
elasticity to the target attendance when the crowd is known (else the raw
training mean).  Programme P5 (static top-P, the coverage-relevant part --
timed moves add <1 pt) is scored on the predicted surface and compared with
the oracle (P5 on the realised surface).

Outputs results/deployment_pergame.csv/.tex.
"""
import argparse, re
import numpy as np
import pandas as pd


def clean_label(lab, kiso):
    m = re.search(r'(\d{4})-(\d{2})-(\d{2})', str(lab) + " " + str(kiso))
    if m:
        y, mo, d = m.groups()
        return pd.Timestamp(int(y), int(mo), int(d)).strftime('%d %b %Y').lstrip('0')
    return str(lab)


def cov_topP(surf, P=5):
    tot = surf.sum(1); top = np.argsort(-tot)[:P]
    return surf[top].sum() / max(surf.sum(), 1e-9)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--surfaces", default="results/surfaces.npz")
    ap.add_argument("--P", type=int, default=5)
    args = ap.parse_args()

    S = np.load(args.surfaces, allow_pickle=True)
    acc = S["acc_fx"]; labels = [str(x) for x in S["labels"]]
    kick = [str(x) for x in S["kickoffs"]]; crowds = S["crowds"].astype(float)
    F = len(acc)
    rows = []
    for f in range(F):
        others = [g for g in range(F) if g != f]
        base = np.mean([acc[g] for g in others], axis=0)
        cf = crowds[f]
        known = np.array([crowds[g] for g in others], float)
        # crowd elasticity (log-log) on training games with known crowd + volume
        pred = base.copy()
        if np.isfinite(cf):
            kk_mask = np.isfinite(known)
            if kk_mask.sum() >= 3:
                xg = np.log(known[kk_mask] + 1)
                yg = np.log(np.array([acc[g].sum() for g in others])[kk_mask] + 1)
                beta = float(np.clip(np.polyfit(xg, yg, 1)[0], 0, 1))
                scale = (cf / np.mean(known[kk_mask])) ** beta
                pred = base * scale
        realised = acc[f]
        rows.append(dict(
            fixture=labels[f], kickoff=kick[f],
            crowd=("" if not np.isfinite(cf) else int(cf)),
            realised_events=int(realised.sum()),
            cov_oracle=round(cov_topP(realised, args.P), 4),
            cov_pred=round(cov_topP(pred, args.P) if pred.sum() > 0 else np.nan, 4),
        ))
    pg = pd.DataFrame(rows)
    pg.to_csv("results/deployment_pergame.csv", index=False)

    body = "\n".join(
        f"{i+1} & {clean_label(r.fixture, r.kickoff)} & {r.kickoff[11:16]} & "
        f"{r.crowd if r.crowd!='' else '--'} & {r.realised_events} & "
        f"{100*r.cov_oracle:.1f} & {100*r.cov_pred:.1f} \\\\"
        for i, r in pg.iterrows())
    tex = (
        "% deployment_pergame.tex - generated by 53_pergame.py\n"
        "\\begin{table}[htbp]\n\\centering\n\\begin{footnotesize}\n"
        "\\begin{tabular}{rlrrrrr}\n\\toprule\n"
        "\\# & Fixture & Kick-off & Crowd & Brake events & Oracle (\\%) & Predictive (\\%) \\\\\n"
        "\\midrule\n" + body +
        f"\n\\midrule\n\\multicolumn{{5}}{{l}}{{Mean ({F} fixtures)}} & "
        f"{100*pg.cov_oracle.mean():.1f} & {100*pg.cov_pred.mean():.1f} \\\\\n"
        "\\bottomrule\n\\end{tabular}\\end{footnotesize}\n"
        "\\captionsetup{margin={0.5in,0in}}\n"
        "\\caption{\\textcolor{Highlight}{Leave-one-fixture-out rosters for the real Suncorp "
        "fixtures.} Predictive solves P5 on the attendance-rescaled mean of the other fixtures; "
        "Oracle solves on the realised surface.}\n"
        "\\label{tab:pergame}\n\\end{table}\n")
    open("results/deployment_pergame.tex", "w").write(tex)
    print(f"[53] {F} fixtures | oracle {100*pg.cov_oracle.mean():.1f}% "
          f"pred {100*pg.cov_pred.mean():.1f}% -> deployment_pergame.csv/.tex")


if __name__ == "__main__":
    main()
